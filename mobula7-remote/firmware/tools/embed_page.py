#!/usr/bin/env python3
"""Embed web/control.html into mobula7_tx/control_page.h for the TX sketch.

Usage:
  python3 tools/embed_page.py          # regenerate the header
  python3 tools/embed_page.py --check  # exit 1 if the header is stale
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "web" / "control.html"
DST = ROOT / "mobula7_tx" / "control_page.h"
DELIM = "M7PAGE"


def render() -> str:
    html = SRC.read_text(encoding="utf-8")
    if f"){DELIM}\"" in html:
        raise SystemExit(f"control.html contains the raw-string delimiter {DELIM}")
    return (
        "// Generated by tools/embed_page.py from web/control.html. Do not edit.\n"
        "#pragma once\n"
        "#include <pgmspace.h>\n\n"
        f'static const char CONTROL_PAGE[] PROGMEM = R"{DELIM}({html}){DELIM}";\n'
    )


def main() -> int:
    want = render()
    if "--check" in sys.argv[1:]:
        have = DST.read_text(encoding="utf-8") if DST.exists() else ""
        if have != want:
            print(f"{DST.relative_to(ROOT)} is stale; run tools/embed_page.py")
            return 1
        print("control_page.h is up to date")
        return 0
    DST.write_text(want, encoding="utf-8")
    print(f"wrote {DST.relative_to(ROOT)} ({len(want)} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
